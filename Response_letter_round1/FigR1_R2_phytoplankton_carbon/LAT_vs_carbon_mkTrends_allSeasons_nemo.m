%% -- Local function: Sen's-slope trend + R^2/p per lat row, matching plotTrendsNPP.m
%% (the function behind f2_plot_combine_NPP_nemo.m, the authoritative combined-figure
%% script) exactly -- skip a row only if ALL years are NaN, not if ANY year is NaN.
%% A stricter any-NaN guard was tried earlier and found to silently blank 5 real,
%% ktaub-computable Winter/NEMO rows (lat -51.5 to -55.5) that the authoritative
%% script does plot -- caught 2026-07-23 when the user noticed the Winter panel
%% still looked "a little different" from the paper. abs() in the denominator also
%% added for exact parity (a no-op here since NPP/carbon are always positive).
function [sen_slope, p_value, r_square] = lat_sen_trend(lat_var, L)
nlat = size(lat_var, 1);
sen_slope = nan(nlat, 1);
p_value = nan(nlat, 1);
r_square = nan(nlat, 1);
for i = 1:nlat
    y = lat_var(i, :);
    if sum(~isnan(y)) == 0
        continue
    end
    datain = [(1:L)', y'];
    [~, ~, ~, sig, ~, ~, ~, ~, ~, plotofslope, ~] = ktaub(datain, 0.9999, 1);
    if ~isnan(plotofslope)
        sen_slope(i) = single((plotofslope(2,2) - plotofslope(1,2)) / abs(plotofslope(1,2)) * 100);
        SSres = sum((y' - plotofslope(:,2)).^2, 'omitnan');
        SStot = sum((y' - nanmean(y')).^2, 'omitnan');
        r_square(i) = 1 - SSres/SStot;
    end
    p_value(i) = sig;
end
end
