% Used for: latitudinal trends with both thresholds, mldLat_trend_comparison_d125_vs_003.csv (SI Fig. S1)
% Original: Manuscript\MLD\manuscript\nature\NCC\R1\code for revision\mld_d125\compare_mldLat_trends_d125_vs_d03.m (data paths updated to I:\Prj; computation unchanged)
% compare_mldLat_trends_d125_vs_d03.m
%
% Compares the LATITUDINAL MLD trend (Sen's slope / Mann-Kendall, %/yr,
% same methodology as the manuscript's own established
% Code\mld_NEMO\LAT_vs_MLDmkTrends_season.m) between the 0.03 kg/m^3
% threshold (mldLat_season.mat, established) and the 0.125 kg/m^3
% Reviewer-1 sensitivity threshold (mldLat_season_d125.mat, generated by
% biomes_1M_d125_ot.m + latSeason_d125_ot.m -- the IDENTICAL two-stage
% pipeline as the 0.03 product, not a full-grid shortcut, per user
% request 2026-07-25).
%
% Trend method (matches LAT_vs_MLDmkTrends_season.m exactly): for each
% 1-deg latitude band within [-60,60] (poleward excluded, same convention
% used throughout this project), Theil-Sen/Mann-Kendall slope via
% ktaub.m at alpha=0.9999, normalized to %/yr as
% (fitted_end - fitted_start)/|fitted_start| * 100. One point per
% lat-season pair in the scatter, colored by season, styled like
% fig_d125_vs_003_comparison.png (the biome-level 0.125-vs-0.03
% comparison already built for this same reviewer request).
%
% Output: mldLat_trend_comparison_d125_vs_003.csv (this folder) -- consumed
% by plot_mldLat_trend_comparison_d125_vs_003_seasonal.m, the actual
% figure-generating script (1x4 seasonal-panel version, styled after the
% manuscript's Figure 5). This script's own combined-scatter plot was
% removed 2026-07-26 once the seasonal-panel figure superseded it, to
% avoid two plotting scripts drifting apart in style.
%
% Haipeng Zhao
% 2026-07-25

clear; close all; clc;
addpath('D:\Users\zhp19\OneDrive - Indiana State University\Research\MATLAB toolbox\ktaub');
DIR = fileparts(mfilename('fullpath'));

D003 = load('I:\Prj\MLD_1M_NEMO\mldLat_season.mat');
D125 = load(fullfile(DIR,'mldLat_season_d125.mat'));

lat_full = D003.lat(:);
assert(isequal(lat_full, D125.lat(:)), 'lat grids differ between 0.03 and 0.125 -- must match');
idx = lat_full <= 60 & lat_full >= -60;
lat = lat_full(idx);
L = 20;

seasons = {'Spring','Summer','Autumn','Winter'};
fields  = {'mldspLat','mldsuLat','mldauLat','mldwiLat'};

results = struct('lat',{},'season',{},'trend003',{},'p003',{},'trend125',{},'p125',{},'sign_agree',{});

for s = 1:4
    y003 = D003.(fields{s})(idx,:);
    y125 = D125.(fields{s})(idx,:);

    for i = 1:numel(lat)
        y3 = y003(i,:); y1 = y125(i,:);

        t3 = NaN; p3 = NaN;
        if sum(isfinite(y3)) == L
            datain = [(1:L)', y3'];
            [~,~,~,sig,~,~,~,~,~,plotofslope,~] = ktaub(datain, 0.9999, 1);  % wantplot=1 required --
                 % ktaub.m only computes senplot (the Sen's-slope line, needed below) when
                 % wantplot~=0; its actual figure/plot commands are commented out internally
                 % (verified by reading the source), so this is a pure data-computation flag
                 % here, not a real plot -- safe in -batch mode. Matches the established
                 % LAT_vs_MLDmkTrends_season.m call exactly (bug found+fixed 2026-07-26: an
                 % earlier version of this script incorrectly passed wantplot=0, which silently
                 % made every trend NaN and produced a 0-point comparison).
            if ~isnan(plotofslope)
                t3 = (plotofslope(2,2) - plotofslope(1,2)) / abs(plotofslope(1,2)) * 100;
            end
            p3 = sig;
        end

        t1 = NaN; p1 = NaN;
        if sum(isfinite(y1)) == L
            datain = [(1:L)', y1'];
            [~,~,~,sig,~,~,~,~,~,plotofslope,~] = ktaub(datain, 0.9999, 1);  % wantplot=1 required --
                 % ktaub.m only computes senplot (the Sen's-slope line, needed below) when
                 % wantplot~=0; its actual figure/plot commands are commented out internally
                 % (verified by reading the source), so this is a pure data-computation flag
                 % here, not a real plot -- safe in -batch mode. Matches the established
                 % LAT_vs_MLDmkTrends_season.m call exactly (bug found+fixed 2026-07-26: an
                 % earlier version of this script incorrectly passed wantplot=0, which silently
                 % made every trend NaN and produced a 0-point comparison).
            if ~isnan(plotofslope)
                t1 = (plotofslope(2,2) - plotofslope(1,2)) / abs(plotofslope(1,2)) * 100;
            end
            p1 = sig;
        end

        if isnan(t3) || isnan(t1)
            continue
        end
        results(end+1) = struct('lat',lat(i),'season',seasons{s}, ...
            'trend003',t3,'p003',p3,'trend125',t1,'p125',p1, ...
            'sign_agree', sign(t3)==sign(t1)); %#ok<SAGROW>
    end
    fprintf('%s done (%d/%d lat bands both finite)\n', seasons{s}, ...
        sum(strcmp({results.season},seasons{s})), numel(lat));
end

T = struct2table(results);
writetable(T, fullfile(DIR,'mldLat_trend_comparison_d125_vs_003.csv'));

fprintf('\n=== Summary ===\n');
fprintf('Total lat-season points: %d\n', height(T));
fprintf('Sign agreement: %d/%d (%.0f%%)\n', sum(T.sign_agree), height(T), 100*mean(T.sign_agree));
rr = corrcoef(T.trend003, T.trend125);
fprintf('Correlation (0.03 vs 0.125): r=%.3f\n', rr(1,2));
fprintf('\nRun plot_mldLat_trend_comparison_d125_vs_003_seasonal.m for the figure.\n');
